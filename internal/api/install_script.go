package api

import (
	"io"
	"text/template"
)

// installShTmpl is the Linux and macOS installer. It runs from a pipe, as
// sh's standard input, so it reads the token it asks for from the terminal.
// sigilc gets the token through its environment, which unlike its command
// line other users cannot read. On a host where the sigilc service is
// installed, it stops the service before it replaces sigilc, and installs the
// service anew after enrolling, since kardianos does not install over one.
var installShTmpl = template.Must(template.New("install.sh").Parse(`#!/bin/sh
# Sigil client installer, generated by sigils. Run it as root:
#   {{ .WithToken }}
# installs sigilc and enrolls it with the token or, where sigilc is
# installed, installs it again and enrolls it anew. For the name of an
# enrolled client, create the token with
#   sigils token create --name <name> --replace
# Without --token, the installer asks for the token on the terminal, which
# keeps it off the command line: prefer this on a host that others use.
#   {{ .AskToken }}
# With --upgrade, it replaces sigilc on a host where it is installed and
# restarts its service, which keeps its enrollment.
#   {{ .Upgrade }}
set -e

SERVER_URL="{{ .ServerURL }}"
DEST=/usr/local/bin/sigilc
TOKEN=""
UPGRADE=""

usage() {
  echo "usage: sh install.sh [--token <TOKEN>]  install sigilc, or install it again with a new token" >&2
  echo "       sh install.sh --upgrade           replace sigilc and restart its service" >&2
  echo "Without --token, the token is read from the terminal. For the name of an enrolled" >&2
  echo "client, create the token with: sigils token create --name <name> --replace" >&2
  exit 2
}

# sigilc is enrolled when this runs, and running the installer again would
# need a new token: the rest of the reinstall is left to do by hand.
service_failed() {
  echo "sigilc is enrolled, but its service is not installed anew. Once the error above is fixed, run" >&2
  echo "  sudo $DEST service uninstall    (if the service of the earlier install is still there)" >&2
  echo "  sudo $DEST service install && sudo $DEST service start" >&2
  exit 1
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --token)
      if [ "$#" -lt 2 ]; then usage; fi
      TOKEN="$2"
      shift 2
      ;;
    --upgrade) UPGRADE=1; shift ;;
    *) usage ;;
  esac
done
if [ -n "$UPGRADE" ] && [ -n "$TOKEN" ]; then usage; fi

# A signal ends the installer through exit, which runs the EXIT traps below:
# they restore the terminal and remove the download.
trap 'exit 1' HUP INT TERM

if [ -z "$UPGRADE" ] && [ -z "$TOKEN" ]; then
  if ! (: </dev/tty) 2>/dev/null; then
    echo "No terminal to read the token from: pass --token <TOKEN>." >&2
    exit 2
  fi
  echo "For the name of an enrolled client, create the token with --replace." >/dev/tty
  printf 'Enrollment token: ' >/dev/tty
  trap 'stty echo </dev/tty' EXIT
  stty -echo </dev/tty
  read -r TOKEN </dev/tty || :
  stty echo </dev/tty
  trap - EXIT
  echo >/dev/tty
  if [ -z "$TOKEN" ]; then usage; fi
fi

OS=$(uname -s | tr '[:upper:]' '[:lower:]')
ARCH=$(uname -m)
case "$ARCH" in
  x86_64) ARCH=amd64 ;;
  aarch64|arm64) ARCH=arm64 ;;
  i386|i686) ARCH=386 ;;
esac

# One rename puts the download in the place of the installed sigilc: a
# download that fails leaves that as it was, and a sigilc that runs keeps the
# file it started from. -q, first, keeps root's ~/.curlrc out of it.
TMP=$(mktemp "$DEST.XXXXXX")
trap 'rm -f "$TMP"' EXIT
echo "Downloading sigilc for $OS/$ARCH..."
curl -q -fsSL --proto '=https' --proto-redir '=https' "$SERVER_URL/download/sigilc?os=$OS&arch=$ARCH" -o "$TMP"
chmod 0755 "$TMP"
# A sigilc that does not run fails here, before anything changes.
"$TMP" version

# The service of an earlier install is stopped before sigilc is replaced,
# and installed anew after the enrollment: kardianos refuses to install over
# the file that defines it, under systemd or launchd, whatever its state.
INSTALLED=""
for f in /etc/systemd/system/sigilc.service /Library/LaunchDaemons/sigilc.plist; do
  if [ -e "$f" ]; then INSTALLED=1; fi
done
if [ -n "$UPGRADE" ] && [ -z "$INSTALLED" ]; then
  echo "The sigilc service is not installed on this host: install sigilc with a token." >&2
  exit 1
fi

if [ -n "$INSTALLED" ]; then
  echo "Stopping service..."
  "$TMP" service stop
fi
mv -f "$TMP" "$DEST"

if [ -z "$UPGRADE" ]; then
  echo "Enrolling..."
  if ! SIGILC_TOKEN="$TOKEN" "$DEST" enroll; then
    # An enrollment that fails before the server takes the token, such as
    # for a token of another name, leaves client.yaml and its identity as
    # they were: the service goes on.
    if [ -n "$INSTALLED" ]; then
      if "$DEST" service start; then
        echo "Enrolling failed. The sigilc service runs again with its earlier client.yaml; fix what the error above says, then run the installer again." >&2
      else
        echo "Enrolling failed, and so did starting the sigilc service again with its earlier client.yaml: see both errors above." >&2
      fi
      echo "Where the error says that the server took the token, the earlier identity no longer works: create a token with sigils token create --name <name> --replace." >&2
    fi
    exit 1
  fi
  if [ -n "$INSTALLED" ]; then
    echo "Uninstalling the service of the earlier install..."
    "$DEST" service uninstall || service_failed
  fi
  echo "Installing system service..."
  "$DEST" service install || service_failed
fi

echo "Starting service..."
"$DEST" service start
# The service manager starts a daemon that then fails, such as on a
# client.yaml it cannot load, as well: the daemon runs once it answers.
i=0
until STATUS=$("$DEST" status 2>/dev/null); do
  i=$((i + 1))
  if [ "$i" -ge 15 ]; then
    echo "The sigilc daemon did not start within 15 seconds: see journalctl -u sigilc (on macOS, /var/log/sigilc.err.log)." >&2
    exit 1
  fi
  sleep 1
done
echo "$STATUS"

echo "Done."
`))

// installPs1Tmpl is the Windows installer. It holds only ASCII, which reads
// the same in every encoding Windows PowerShell 5.1 may assume for it. It runs
// as a script block in the operator's own session, which exit would close, so
// every failure throws instead: a cmdlet's through $ErrorActionPreference, and
// sigilc's through its exit code, which PowerShell does not check by itself.
// Its steps are those of install.sh, and two that Windows needs: before it
// replaces sigilc.exe, it waits for the process of the stopped service to
// exit, and a reinstall writes back the Environment of the service, which
// the uninstall deletes.
var installPs1Tmpl = template.Must(template.New("install.ps1").Parse(`# Sigil client installer for Windows, generated by sigils.
# Run it in an elevated Windows PowerShell 5.1 or PowerShell 7:
#   {{ .WithToken }}
# installs sigilc and enrolls it with the token or, where sigilc is
# installed, installs it again and enrolls it anew. For the name of an
# enrolled client, create the token with
#   sigils token create --name <name> --replace
# Without -Token, the installer asks for the token, which keeps it out of
# the command history:
#   {{ .AskToken }}
# With -Upgrade, it replaces sigilc on a host where it is installed and
# restarts its service, which keeps its enrollment.
#   {{ .Upgrade }}
param([string]$Token, [switch]$Upgrade)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$Principal = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
if (-not $Principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'Run this installer in an elevated PowerShell (Run as administrator).'
}
if ($Upgrade -and $Token) {
    throw 'Give either -Token or -Upgrade.'
}
if (-not $Upgrade -and -not $Token) {
    Write-Host 'For the name of an enrolled client, create the token with --replace.'
    $SecureToken = Read-Host -Prompt 'Enrollment token' -AsSecureString
    $Token = [Net.NetworkCredential]::new('', $SecureToken).Password
    if (-not $Token) { throw 'No enrollment token given.' }
}

$ServerURL = '{{ .ServerURL }}'

$MachineArch = if ($env:PROCESSOR_ARCHITEW6432) { $env:PROCESSOR_ARCHITEW6432 } else { $env:PROCESSOR_ARCHITECTURE }
$Arch = switch ($MachineArch.ToUpperInvariant()) {
    'AMD64' { 'amd64' }
    'ARM64' { 'arm64' }
    'X86'   { '386' }
    default { throw "Unsupported Windows architecture: $MachineArch" }
}

$Dest = 'C:\Program Files\Sigil\sigilc.exe'
# The download goes beside sigilc.exe, which it replaces in one step: a
# download that fails leaves the installed sigilc.exe as it was. PowerShell
# runs a file only if its name ends in .exe.
$Download = 'C:\Program Files\Sigil\sigilc.download.exe'
# The service of an earlier install is stopped before sigilc.exe is
# replaced, which Windows does not allow while it runs, and installed anew
# after the enrollment, since it cannot be installed over.
$Service = Get-Service -Name sigilc -ErrorAction SilentlyContinue
if ($Upgrade -and -not $Service) {
    throw 'The sigilc service is not installed on this host: install sigilc with a token.'
}

New-Item -ItemType Directory -Force -Path (Split-Path $Dest) | Out-Null

try {
    Write-Host "Downloading sigilc for windows/$Arch..."
    Invoke-WebRequest -UseBasicParsing -Uri "$ServerURL/download/sigilc?os=windows&arch=$Arch" -OutFile $Download
    # A sigilc that does not run fails here, before anything changes.
    & $Download version
    if ($LASTEXITCODE -ne 0) { throw "the downloaded sigilc failed with exit code $LASTEXITCODE" }

    if ($Service) {
        # Stop-Service returns once the SCM reports the service stopped,
        # which may be before its process exits: ReplaceFile then cannot
        # delete the sigilc.exe that process runs, and leaves it beside the
        # new one as sigilc.exe~RF*.TMP.
        $ServicePid = (Get-CimInstance -ClassName Win32_Service -Filter "Name='sigilc'").ProcessId
        $ServiceProcess = if ($ServicePid) { Get-Process -Id $ServicePid }
        Write-Host 'Stopping service...'
        Stop-Service -Name sigilc
        if ($ServiceProcess -and -not $ServiceProcess.WaitForExit(30000)) {
            throw "Process $ServicePid of the sigilc service did not exit within 30 seconds of the service stopping: sigilc.exe is not replaced, and the service stays stopped. Once that process has exited, run the installer again."
        }
    }
    if (Test-Path -LiteralPath $Dest) {
        # PowerShell would pass $null to it as an empty path.
        [IO.File]::Replace($Download, $Dest, [NullString]::Value)
    } else {
        Move-Item -LiteralPath $Download -Destination $Dest
    }
} finally {
    # What a download or a sigilc that failed left.
    if (Test-Path -LiteralPath $Download) { Remove-Item -LiteralPath $Download }
}

if (-not $Upgrade) {
    Write-Host 'Enrolling...'
    # sigilc gets the token through its environment, which unlike its
    # command line other users cannot read. It is set in the operator's
    # session, which keeps it until it is removed.
    $env:SIGILC_TOKEN = $Token
    try {
        & $Dest enroll
        if ($LASTEXITCODE -ne 0) { throw "sigilc enroll failed with exit code $LASTEXITCODE" }
    } catch {
        # An enrollment that fails before the server takes the token, such
        # as for a token of another name, leaves client.yaml and its identity
        # as they were: the service goes on.
        $EnrollError = $_
        if (-not $Service) { throw }
        $TokenTaken = 'Where the error says that the server took the token, the earlier identity no longer works: ' +
            'create a token with sigils token create --name <name> --replace.'
        Write-Host 'Starting the service of the earlier install again...'
        & $Dest service start
        if ($LASTEXITCODE -ne 0) { throw "$EnrollError; starting the sigilc service again with its earlier client.yaml failed too, with exit code $LASTEXITCODE. $TokenTaken" }
        throw "$EnrollError. The sigilc service runs again with its earlier client.yaml; fix what the error says, then run the installer again. $TokenTaken"
    } finally {
        Remove-Item -Path Env:\SIGILC_TOKEN
    }
    # sigilc is enrolled by now, and running the installer again would need a
    # new token: the rest of the reinstall is left to do by hand.
    $ServiceKey = 'HKLM:\SYSTEM\CurrentControlSet\Services\sigilc'
    $SetEnvironment = ''
    if ($Service) {
        # The uninstall deletes the registry key of the service, and with it
        # its Environment, which gives the ${VAR}s of client.yaml their
        # values: it is written back once the service is installed anew, and
        # what is left to do by hand says how. The values may be secrets,
        # which no message shows: it names only the variables.
        $Environment = (Get-Item -LiteralPath $ServiceKey).GetValue('Environment')
        if ($null -ne $Environment) {
            $Variables = ($Environment | ForEach-Object { "'" + ($_ -split '=', 2)[0] + "=<value>'" }) -join ', '
            $SetEnvironment = " Before that start, give the service its Environment back, with the values it had: " +
                "New-ItemProperty -LiteralPath '$ServiceKey' -Name Environment -PropertyType MultiString -Force -Value @($Variables)"
        }
        Write-Host 'Uninstalling the service of the earlier install...'
        & $Dest service uninstall
        if ($LASTEXITCODE -ne 0) { throw "sigilc service uninstall failed with exit code $LASTEXITCODE. sigilc is enrolled: once that is fixed, run & '$Dest' service uninstall, then & '$Dest' service install and & '$Dest' service start.$SetEnvironment" }
    }
    Write-Host 'Installing system service...'
    & $Dest service install
    if ($LASTEXITCODE -ne 0) { throw "sigilc service install failed with exit code $LASTEXITCODE. sigilc is enrolled: once that is fixed, run & '$Dest' service install, then & '$Dest' service start.$SetEnvironment" }
    if ($Service -and $null -ne $Environment) {
        try {
            New-ItemProperty -LiteralPath $ServiceKey -Name Environment -PropertyType MultiString -Value ([string[]]$Environment) | Out-Null
        } catch {
            throw "Writing back the Environment of the sigilc service failed: $($_.Exception.Message). sigilc is enrolled and its service installed: once that is fixed, run & '$Dest' service start.$SetEnvironment"
        }
    }
}

Write-Host 'Starting service...'
& $Dest service start
if ($LASTEXITCODE -ne 0) { throw "sigilc service start failed with exit code $LASTEXITCODE" }
# The SCM starts a daemon that then fails, such as on a client.yaml it cannot
# load, as well: the daemon runs once it answers. Until then sigilc status
# fails, and says why on stderr, which is no error of the installer.
$Deadline = (Get-Date).AddSeconds(15)
do {
    Start-Sleep -Seconds 1
    $Status = & { $ErrorActionPreference = 'Continue'; & $Dest status 2>$null }
} until ($LASTEXITCODE -eq 0 -or (Get-Date) -gt $Deadline)
if ($LASTEXITCODE -ne 0) { throw 'The sigilc daemon did not start within 15 seconds: see the Application event log, source sigilc.' }
$Status | ForEach-Object { Write-Host $_ }

Write-Host 'Done.'
`))

// usageToken stands for the token in the usage comments of the scripts.
const usageToken = "<TOKEN>"

// installData is what the templates of the install scripts take: the base URL
// of the server, and the commands that run the script with a token, asking
// for the token, and to upgrade.
type installData struct {
	ServerURL                    string
	WithToken, AskToken, Upgrade string
}

// usages returns the data of install.sh and install.ps1.
func usages(serverURL string) (sh, ps1 installData) {
	sh.ServerURL, ps1.ServerURL = serverURL, serverURL
	sh.WithToken, ps1.WithToken = InstallCommands(serverURL, usageToken)
	sh.AskToken, ps1.AskToken = installCommands(serverURL, "", "")
	sh.Upgrade, ps1.Upgrade = installCommands(serverURL, " -s -- --upgrade", " -Upgrade")
	return sh, ps1
}

func renderInstallSh(w io.Writer, serverURL string) {
	sh, _ := usages(serverURL)
	_ = installShTmpl.Execute(w, sh)
}

// renderInstallPs1 writes the Windows installer, which is the same for every
// request: the token reaches it as the -Token argument, or as the answer to
// its prompt for it, never through the server.
func renderInstallPs1(w io.Writer, serverURL string) {
	_, ps1 := usages(serverURL)
	_ = installPs1Tmpl.Execute(w, ps1)
}
